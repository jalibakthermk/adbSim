// Regenerates data/demo/ from src/core/demo.js.  Run from the repo root:  node tools/gen-demo.js
import { writeFileSync, mkdirSync } from 'node:fs';
import { writeIES } from '../src/core/ies.js';
import { demoLowBeam, demoHighBeam, demoSegments, DEMO_SEGMENT_EDGES, DEMO_SOFT_EDGE } from '../src/core/demo.js';

const dir = new URL('../data/demo/', import.meta.url);
mkdirSync(dir, { recursive: true });
const put = (name, ies) => writeFileSync(new URL(name, dir), writeIES(ies, { decimals: 1 }));

put('low_beam.ies', demoLowBeam(false));
put('high_beam.ies', demoHighBeam());
const segments = demoSegments().map((s, i) => {
  const file = `segment_${String(i + 1).padStart(2, '0')}.ies`;
  put(file, s);
  return { file, H: [DEMO_SEGMENT_EDGES[i], DEMO_SEGMENT_EDGES[i + 1]] };
});

writeFileSync(new URL('segments.json', dir), JSON.stringify({
  note: 'Synthetic demo beams generated by tools/gen-demo.js. Type A, H+ = right. Same files are used for the left and right lamp.',
  lowBeam: 'low_beam.ies',
  highBeam: 'high_beam.ies',
  edges: DEMO_SEGMENT_EDGES,
  softEdge_deg: DEMO_SOFT_EDGE,
  segments,
}, null, 2) + '\n');

console.log(`Wrote low beam, high beam and ${segments.length} segments to data/demo/`);
